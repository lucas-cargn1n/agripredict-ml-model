import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt

# 1. Carregar os dados (supondo que você subiu o arquivo csv no Colab)
df = pd.read_csv('Crop_recommendation.csv')

# 2. Inspecionar os dados
display(df.head())
print(df.info())

# 3. Estatísticas descritivas (para ver mínimos, máximos e médias de nutrientes)
display(df.describe())

# 4. Verificar correlações (ex: temperatura vs umidade)
plt.figure(figsize=(10, 8))
sns.heatmap(df.corr(numeric_only=True), annot=True, cmap='coolwarm')
plt.title("Matriz de Correlação das Features Agrícolas")
plt.show()

# 5. Distribuição das culturas
plt.figure(figsize=(15, 6))
sns.countplot(data=df, x='label')
plt.xticks(rotation=90)
plt.title("Contagem de Culturas no Dataset")
plt.show()

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, LabelEncoder

# Separar Features (X) e Target (y)
X = df.drop('label', axis=1)
y = df['label']

# Codificar os rótulos de texto para números (opcional dependendo do modelo, mas recomendado)
encoder = LabelEncoder()
y_encoded = encoder.fit_transform(y)

# Dividir em Treino (80%) e Teste (20%)
X_train, X_test, y_train, y_test = train_test_split(X, y_encoded, test_size=0.2, random_state=42)

# Padronizar a escala das variáveis (importante para modelos baseados em distância ou redes neurais)
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

from sklearn.ensemble import RandomForestClassifier
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score

# --- Modelo 1: Random Forest ---
rf_model = RandomForestClassifier(n_estimators=100, random_state=42)
rf_model.fit(X_train_scaled, y_train)
rf_preds = rf_model.predict(X_test_scaled)

# --- Modelo 2: MLP (Rede Neural) ---
mlp_model = MLPClassifier(hidden_layer_sizes=(100, 50), max_iter=500, random_state=42)
mlp_model.fit(X_train_scaled, y_train)
mlp_preds = mlp_model.predict(X_test_scaled)

print("--- Resultados Random Forest ---")
print(f"Acurácia: {accuracy_score(y_test, rf_preds):.4f}")

print("\n--- Resultados MLP ---")
print(f"Acurácia: {accuracy_score(y_test, mlp_preds):.4f}")
print("\nRelatório de Classificação (MLP):")
print(classification_report(y_test, mlp_preds, target_names=encoder.classes_))

# Visualizar Matriz de Confusão do melhor modelo
plt.figure(figsize=(12, 10))
cm = confusion_matrix(y_test, mlp_preds)
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', xticklabels=encoder.classes_, yticklabels=encoder.classes_)
plt.title("Matriz de Confusão - Rede Neural (MLP)")
plt.ylabel('Verdadeiro')
plt.xlabel('Previsto')
plt.show()

